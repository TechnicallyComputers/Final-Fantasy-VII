static unsigned half(uint32_t p){return psx_mod_read_byte(p)|((unsigned)psx_mod_read_byte(p+1)<<8);}
static void bytes(uint32_t p,const uint8_t* in,size_t n){for(size_t i=0;i<n;++i)psx_mod_write_byte(p+(uint32_t)i,in[i]);}
static int guard(const MotionSite* site){for(unsigned j=0;j<13;++j)if(psx_mod_read_word(site->pc-24+4*j)!=site->words[j])return 0;return 1;}
int ff7_party_motion_init(void){
    s_motions=psx_mod_alloc_guest_memory(3*SLOT_BYTES,16);
    if(!s_motions)return 0;
    for(unsigned i=0;i<3;++i)ff7_party_motion_clear(i);
    return 1;
}
void ff7_party_motion_clear(unsigned slot){if(s_motions && slot<3)psx_mod_write_word(s_motions+slot*SLOT_BYTES+ARENA_BYTES,0);}
int ff7_party_motion_prepare(unsigned slot,uint32_t model,unsigned policy){
    const FF7PartyMotionPolicy* p=ff7_party_motion_policy(policy);
    if(!s_motions || slot>=3 || !p)return 0;
    ff7_party_motion_clear(slot);
    for(unsigned i=0;i<sizeof sites/sizeof sites[0];++i)if(!guard(&sites[i]))return 0;
    uint8_t* original=malloc(p->body_bytes);uint8_t* result=malloc(ARENA_BYTES);
    FF7MotionPose* poses=malloc(2*FF7_MOTION_FRAMES*sizeof *poses);
    int ok=0;size_t used=0;uint32_t offsets[3][2];
    if(!original || !result || !poses)goto done;
    uint32_t crc=~0u;
    for(unsigned i=0;i<p->body_bytes;++i){original[i]=psx_mod_read_byte(model+i);crc^=original[i];
        for(unsigned j=0;j<8;++j)crc=(crc>>1)^((0u-(crc&1u))&0xedb88320u);}
    if(~crc!=p->body_crc)goto done;
    for(unsigned role=0;role<3;++role){
        FF7MotionPose seed[2];
        for(unsigned bank=0;bank<2;++bank){
            uint32_t at=psx_mod_read_word(model+12+4u*(p->source[role]+52u*bank));
            if(at>=p->body_bytes || !ff7_motion_decode_frame(original+at,p->body_bytes-at,bank?1:p->rotations,p->source_frame[role],&seed[bank]))goto done;
        }
        if(!ff7_motion_synthesize((FF7MotionRole)role,&seed[0],&seed[1],poses,poses+FF7_MOTION_FRAMES))goto done;
        for(unsigned bank=0;bank<2;++bank){
            offsets[role][bank]=(uint32_t)used;
            size_t n=ff7_motion_encode(poses+bank*FF7_MOTION_FRAMES,FF7_MOTION_FRAMES,bank?1:p->rotations,result+used,ARENA_BYTES-used);
            if(!n)goto done;
            used+=n;
        }
    }
    uint32_t arena=s_motions+slot*SLOT_BYTES,control=arena+ARENA_BYTES;
    bytes(arena,result,used);
    for(unsigned role=0;role<3;++role)for(unsigned bank=0;bank<2;++bank)
        psx_mod_write_word(model+12+4u*(p->target[role]+52u*bank),arena+offsets[role][bank]-model);
    psx_mod_write_byte(model+p->near_death_script,p->target[FF7_MOTION_LOW_HP]);
    psx_mod_write_byte(model+p->death_script,p->target[FF7_MOTION_DEATH]);
    psx_mod_write_word(control+4,model);psx_mod_write_word(control+8,0);psx_mod_write_word(control+12,p->target[FF7_MOTION_DEFEND]);
    psx_mod_write_word(control,1);ok=1;
done:
    free(original);free(result);free(poses);return ok;
}
static void instruction(CPUState* cpu,uint32_t pc){
    if(!cpu || !s_motions)return;
    pc=(pc&0x1fffffffu)|0x80000000u;unsigned which;
    for(which=0;which<sizeof sites/sizeof sites[0];++which)if(sites[which].pc==pc)break;
    if(which==sizeof sites/sizeof sites[0] || !guard(&sites[which]))return;
    unsigned slot=cpu->gpr[17];if(slot>=3)return;
    uint8_t guest=psx_mod_read_byte(0x801636b8u+16*slot);
    if(!ff7_party_game_is_extra(guest))return;
    uint32_t control=s_motions+slot*SLOT_BYTES+ARENA_BYTES,model=psx_mod_read_word(control+4);
    if(!psx_mod_read_word(control) || cpu->gpr[19]!=model || cpu->gpr[18]!=model+12)return;
    uint32_t actor=0x801518e4u+0xb9cu*slot;
    int defend=cpu->gpr[2]==0 && half(actor+2)==0 && (psx_mod_read_word(0x800f83e4u+0x68u*slot)&0x20u)!=0;
    if(which==0){
        unsigned was=psx_mod_read_word(control+8);
        if((unsigned)defend!=was){
            /* Decoder state contains a bit cursor into the preceding stream.
             * Reset both banks together before changing the selected stream. */
            psx_mod_write_word(actor+0x74,0);psx_mod_write_word(0x800fa6d8u+64*slot,0);
            psx_mod_write_word(control+8,(uint32_t)defend);
        }
    }
    if(defend){cpu->gpr[2]=psx_mod_read_word(control+12);psx_mod_counter_add("ff7.party_motion.defend",1);}
}
void ff7_party_motion_restore(void){/* All generated bytes and decoder-role state live in guest RAM. */}
PSX_MOD_CONSTRUCTOR(register_ff7_party_motion){
    for(unsigned i=0;i<sizeof sites/sizeof sites[0];++i)
        (void)psx_mod_register_instruction_plugin("ff7.party-gameplay",sites[i].pc,sites[i].words[6],instruction);
}
