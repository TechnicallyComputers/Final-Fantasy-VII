"""Guard evidence for portable owned-disc field actor preparation."""
import argparse,gzip,hashlib,json,struct
from collections import Counter
from pathlib import Path
from inspect_ff7_party import Disc,ROOT
from inspect_ff7_animations import decompress_lzs
SITES=[(0x800ba534,'PREPARE'),(0x800ac484,'MODELS')]
def inspect(cue):
    d=Disc(cue)
    counts=Counter();saturated=[];non_script=[]
    try:
        raw=gzip.decompress(d.read('FIELD/FIELD.BIN')[8:])
        for name in d.files:
            if name.startswith('FIELD/')and name.endswith('.DAT'):
                try:dat=decompress_lzs(d.read(name))
                except ValueError:non_script.append(name);continue
                if dat[28:30]!=b'\x02\x05':non_script.append(name);continue
                counts[dat[31]]+=1
                if dat[31]>=16:saturated.append(name)
    finally:d.reader.close()
    rows=[]
    for pc,action in SITES:
        words=struct.unpack_from('<13I',raw,pc-0x800a0000-24)
        rows.append({'address':pc,'expected':words[6],'action':action,'context_start':pc-24,'context_words':list(words)})
    assert struct.unpack_from('<II',raw,0xaa978-0xa0000)==(0x3c05800e,0x24a5a5c8)
    table=(0x800e<<16)+struct.unpack('<h',bytes.fromhex('c8a5'))[0]
    assert table==0x800da5c8
    return {'schema':1,'image':'FIELD/FIELD.BIN','image_sha256':hashlib.sha256(raw).hexdigest(),'sites':rows,
      'bsx_extent_table':{'address':table,'stride':24,'basis':'Original AA978 LUI a1,800E plus AA97C signed ADDIU a1,a1,A5C8; original table is used by the oracle, never synthesized'},
      'native_capacity_evidence':{'field_model_counts':{str(k):counts[k]for k in sorted(counts)},'fields_scanned':sum(counts.values()),'non_script_dat':sorted(non_script),'maximum_original_models':max(counts),'runtime_total_model_limit':16,'saturated_fields_rejected':sorted(saturated),'reason':'Native132-byte field state array has direct80074EA4 accesses;32 renderer auxiliaries do not establish32 safe script model states'},
      'functions':[{'start':a,'end_exclusive':b,'sha256':hashlib.sha256(raw[a-0x800a0000:b-0x800a0000]).hexdigest()}for a,b in((0x800ac35c,0x800acba0),(0x800ba534,0x800ba65c),(0x800adaa4,0x800adc90))],
      'contract':['BA534: a2 original script pointer; replace only after all assets, metadata, script and loader workspace validate','AC484: s1 raw BSX pointer after read/copy; replace with previously prepared merged BSX','CPU PC, return address and all other registers preserved; logical proxies stay in script PC bindings','Native descriptor/packet generation and shared FIELD.TDB texture handling remain original; owned source with local textures rejected']}
def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--disc',type=Path,required=True);p.add_argument('--write',action='store_true');a=p.parse_args();r=inspect(a.disc)
    path=ROOT/'mods/preloaded/packages/ff7.expanded-party/field-loader.evidence.json'
    if a.write:
        path.write_text(json.dumps(r,indent=2)+'\n')
        (ROOT/'src/ff7_party_field_loader_sites.inc').write_text('/* Original owner-disc FIELD guards; generated by inspect_ff7_field_loader.py. */\n'+''.join('{0x%08xu,%s,{%s}},\n'%(s['address'],s['action'],','.join('0x%08xu'%w for w in s['context_words']))for s in r['sites']))
    else:assert r==json.loads(path.read_text())
    print(json.dumps({'sites':len(r['sites']),'status':'verified'}))
if __name__=='__main__':main()
