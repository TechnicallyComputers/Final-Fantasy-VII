"""Inventory original owner-disc BATRES progression seams; no game assets emitted."""
import argparse
import gzip
import hashlib
import json
import struct
from pathlib import Path
from inspect_ff7_party import Disc, ROOT

SITES=[(0x801b0804,'ACTIVE_RECORD'),(0x801b0ad0,'WRITEBACK_RECORD'),
       (0x801b0be4,'RESTORE_RECORD'),(0x801b11a4,'GROWTH_ROW'),
       (0x801b0d40,'RESERVE_RECORD'),(0x801b0d54,'RESERVE_ID'),
       (0x801b0df0,'RESERVE_LOOP')]
FUNCTIONS=[(0x801b0000,0x801b09c0),(0x801b09c0,0x801b0c74),
           (0x801b0d14,0x801b0e20),(0x801b0ef8,0x801b1008),
           (0x801b1008,0x801b108c),(0x801b108c,0x801b118c),
           (0x801b118c,0x801b1204),(0x801b1204,0x801b1564),
           (0x801b1564,0x801b15e4),(0x801b15e4,0x801b16d8),
           (0x801b16d8,0x801b17cc),(0x801b17cc,0x801b193c)]

def inspect(cue):
    d=Disc(Path(cue))
    try:raw=d.read('BATTLE/BATRES.X')
    finally:d.reader.close()
    data=gzip.decompress(raw[8:]);base=0x801b0000
    if len(data)!=struct.unpack_from('<I',raw)[0]:raise ValueError('Invalid BATRES size')
    if hashlib.sha256(data).hexdigest()!='138b71b4c6843eb77a7909263f12166aea597ab8a694dc8ef10a39afe58cc35e':
        raise ValueError('Unsupported original BATRES revision')
    result={'schema':1,'basis':'Original owner-disc MIPS operand analysis and execution',
            'overlay':{'name':'BATRES','base':base,'bytes':len(data),'sha256':hashlib.sha256(data).hexdigest()},
            'sites':[],'functions':[]}
    for pc,action in sorted(SITES):
        guard=list(struct.unpack_from('<13I',data,pc-base-24))
        result['sites'].append(dict(address=pc,expected=guard[6],action=action,guard=guard))
    for start,end in FUNCTIONS:
        result['functions'].append(dict(start=start,end_exclusive=end,
            sha256=hashlib.sha256(data[start-base:end-base]).hexdigest()))
    result['contract']={
      'plugin':'ff7.party-gameplay, developer default-off',
      'lifecycle':'Stateless; canonical guest registry/records own all progress and rewind state',
      'clobbers':{'ACTIVE_RECORD':'s4 independent record offset, s0=8 final search iteration',
        'WRITEBACK_RECORD':'s1 independent record pointer for original HP/MP/status/limit-meter stores',
        'RESTORE_RECORD':'a1 independent destination, at destination+0x38c8 before backup restore search',
        'GROWTH_ROW':'v1=7*profile.growth_identity before original SLL by3; record ID untouched',
        'RESERVE_RECORD':'s3 independent offset; local s5 mask includes extra only when absent from active party',
        'RESERVE_ID':'v0=1 before original branch for registered extra',
        'RESERVE_LOOP':'v0=(s4 < 9+registry_count); original branch/delay slot retained'},
      'policy':'Registered extras are unlocked reserves; stock half-XP policy and native availability remain intact',
      'limits':'Stock kill/use counters persist; custom limit-learning policy remains separate',
      'dependencies':['Resident AP/record adapters','Shared canonical roster/save lifecycle'],
      'scope':'Original NTSC-U all-three-disc BATRES only; no whole-function replacement or native alias changes'}
    return result

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--disc',required=True,type=Path)
    p.add_argument('--write',action='store_true');a=p.parse_args();r=inspect(a.disc)
    if a.write:
        (ROOT/'mods/preloaded/packages/ff7.expanded-party/rewards.evidence.json').write_text(json.dumps(r,indent=2)+'\n')
        lines=['/* Owner-disc BATRES words; generated by inspect_ff7_rewards.py. */']
        for s in r['sites']:
            lines.append(' {0x%08xu,%s,{%s}},'%(s['address'],s['action'],','.join('0x%08xu'%w for w in s['guard'])))
        (ROOT/'src/ff7_party_rewards_sites.inc').write_text('\n'.join(lines)+'\n')
    print(json.dumps({'overlay':r['overlay'],'sites':len(r['sites'])}))
if __name__=='__main__':main()
